// Builds drafts/voice.md from an X replies export: replies you wrote yourself, for the
// replenish skill to copy your style from. Replies that match (or closely resemble) a
// plugin draft are left out, so the reference stays in your own voice.
//
//   node make-voice.js "/path/to/your-x-replies-export.json"
//
// The export is the X API format: { manifest, replies: [{ text, full_text, lang, created_at }] }.
const fs = require("fs");
const path = require("path");

const ABOUT_WORK = 150; // replies about your own work and projects, newest first
const GENERAL = 100; // other replies, newest first, for everyday tone
const MIN_LENGTH = 12;
const SIMILARITY_LIMIT = 0.5;

const source = process.argv[2];
if (!source) {
  console.error('Usage: node make-voice.js "/path/to/replies-export.json"');
  process.exit(1);
}

const draftsDir = path.join(__dirname, "drafts");
const outPath = path.join(draftsDir, "voice.md");

function normalize(text) {
  return text.toLowerCase().replace(/\s+/g, " ").trim();
}

function words(text) {
  return new Set(
    text
      .replace(/https?:\/\/\S+/g, " ")
      .toLowerCase()
      .replace(/[^a-z0-9' ]+/g, " ")
      .split(/\s+/)
      .filter((w) => w.length > 2)
  );
}

function similarity(a, b) {
  let shared = 0;
  for (const w of a) if (b.has(w)) shared += 1;
  const total = a.size + b.size - shared;
  return total === 0 ? 1 : shared / total;
}

// Every plugin draft, written or posted, so plugin text never counts as your own voice.
function pluginTexts() {
  const texts = [];
  for (const f of fs.readdirSync(draftsDir).filter((f) => f.endsWith(".txt"))) {
    texts.push(...fs.readFileSync(path.join(draftsDir, f), "utf8").split("\n").slice(1).filter(Boolean));
  }
  const usedDir = path.join(draftsDir, "used");
  if (fs.existsSync(usedDir)) {
    for (const f of fs.readdirSync(usedDir).filter((f) => f.endsWith(".json"))) {
      for (const item of JSON.parse(fs.readFileSync(path.join(usedDir, f), "utf8"))) texts.push(item.text);
    }
  }
  return texts;
}

const exportData = JSON.parse(fs.readFileSync(source, "utf8"));
const plugin = pluginTexts();
const pluginKeys = new Set(plugin.map(normalize));
const pluginWords = plugin.map(words);

const seen = new Set();
const replies = [];
let skippedPlugin = 0;
for (const r of exportData.replies || []) {
  if (r.lang !== "en") continue;
  // Drop leading @mentions and put multi-line replies on one line.
  const text = (r.full_text || r.text || "").replace(/^(@\w+\s*)+/, "").replace(/\s*\n+\s*/g, " ").trim();
  if (text.length < MIN_LENGTH) continue;
  const key = normalize(text);
  if (seen.has(key)) continue;
  seen.add(key);
  const own = words(text);
  if (pluginKeys.has(key) || pluginWords.some((w) => similarity(own, w) > SIMILARITY_LIMIT)) {
    skippedPlugin += 1;
    continue;
  }
  replies.push({ text, date: r.created_at.slice(0, 10) });
}
replies.sort((a, b) => b.date.localeCompare(a.date));

const workPattern = /\b(build|building|built|working on|work on|project|app|tool|launch|ship|shipping|users?|repo|open.?source|codex|claude|agents?|feedback|trial|indexing|startup|saas)\b/i;
const aboutWork = replies.filter((r) => workPattern.test(r.text)).slice(0, ABOUT_WORK);
const picked = new Set(aboutWork);
const general = replies.filter((r) => !picked.has(r)).slice(0, GENERAL);

// Measured style, so the skill doesn't have to guess.
const all = replies.map((r) => r.text);
const lengths = all.map((t) => t.length).sort((a, b) => a - b);
const pct = (n) => `${Math.round((n / all.length) * 100)}%`;
const count = (re) => all.filter((t) => re.test(t)).length;
const emojiCounts = {};
for (const t of all) for (const e of t.match(/\p{Extended_Pictographic}/gu) || []) emojiCounts[e] = (emojiCounts[e] || 0) + 1;
const topEmoji = Object.entries(emojiCounts)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 5)
  .map(([e]) => e)
  .join(" ");

const stats = [
  `Replies analysed: ${all.length} (English, written by hand; ${skippedPlugin} plugin drafts left out)`,
  `Length: median ${lengths[lengths.length >> 1]} characters, 90% under ${lengths[Math.floor(lengths.length * 0.9)]}`,
  `No final punctuation: ${pct(count(/[^.!?)]$/))}`,
  `Apostrophes dropped (dont, cant, ive, thats, youre...): in ${pct(count(/\b(dont|cant|ive|im|thats|youre|isnt|doesnt|didnt|wont|youd|its a)\b/i))} of replies`,
  `Lowercase "i" as a word: ${pct(count(/(^|\s)i(\s|$)/))}`,
  `Emoji: in ${pct(count(/\p{Extended_Pictographic}/u))} of replies; most used: ${topEmoji || "none"}`,
  `Questions: ${pct(count(/\?/))} contain one`,
  `Exclamation marks: ${pct(count(/!/))}`,
];

const list = (items) => items.map((r) => `- ${r.text}`).join("\n");
const md = `# My voice

Replies I wrote myself on X, before using the plugin. Generated by \`make-voice.js\` from \`${path.basename(source)}\`; rerun it after a new export.

Use these for **style only**: length, tone, casing, punctuation, slang, humour. They're replies to other people's conversations, so don't reuse their topics, facts or wording. Project facts come from \`projects.md\`, and \`../extension/DRAFTING-RULES.md\` wins over anything here.

## Measured style

${stats.map((s) => `- ${s}`).join("\n")}

## Replies about my work (${aboutWork.length}, newest first)

${list(aboutWork)}

## Everyday replies (${general.length}, newest first)

${list(general)}
`;

fs.writeFileSync(outPath, md);
console.log(`Wrote ${outPath}: ${aboutWork.length} work replies, ${general.length} everyday replies, ${skippedPlugin} plugin drafts left out`);
for (const s of stats) console.log("  " + s);
